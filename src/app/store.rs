//! Persistence for deterministic custom-ID to execution-reference mappings.
use serde::{Deserialize, Serialize};
use crate::app::BoxFuture;

/// Identifies which registry owns the execution definition.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum DefinitionKind {
    Page,
    Modal,
}

/// Persisted information needed to route a Discord custom ID back to code.
///
/// Callback closures are never stored. The registered Page or Modal retains
/// the callback; this record restores its definition, execution, and data.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct StoreRecord {
    /// Deterministic identifier sent to Discord as the component custom ID.
    pub custom_id: String,
    /// Whether the owning definition is a Page or a Modal.
    pub definition_kind: DefinitionKind,
    /// Globally unique ID of the registered definition.
    pub definition_id: String,
    /// Stable execution ID within the Page or Modal definition.
    pub execution_id: String,
    /// Serialized Page or Modal data associated with this rendered instance.
    pub serialized_data: Vec<u8>,
    /// Stable Frame element identity when the execution was generated by a Frame.
    pub frame_identity: Option<String>,
    /// Recoverable pagination position for framework-generated navigation.
    pub pagination_state: Option<serde_json::Value>,
    /// Version of this persisted record format for future migrations.
    pub schema_version: u16,
}

/// Strongly named custom ID used as the Store lookup key.
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub struct CustomId(pub String);

/// Durable persistence contract for execution references.
///
/// Inserting an identical record for an existing ID is idempotent; conflicting
/// content for the same ID is an error. Resolving an unknown ID returns None.
pub trait Store: Send + Sync {
    /// Persists a record, allowing an identical repeated render to reuse it.
    fn insert<'a>(&'a self, record: StoreRecord)
        -> BoxFuture<'a, anyhow::Result<()>>;
    /// Retrieves a record by custom ID, or None when no record exists.
    fn resolve<'a>(&'a self, custom_id: &'a CustomId)
        -> BoxFuture<'a, anyhow::Result<Option<StoreRecord>>>;
    /// Removes a record; removing an already-absent ID is harmless.
    fn remove<'a>(&'a self, custom_id: &'a CustomId)
        -> BoxFuture<'a, anyhow::Result<()>>;
}

/// Derives a deterministic custom ID from the definition, execution, data,
/// and optional stable Frame identity. Equal inputs produce equal IDs; changing
/// any identity input changes the derived ID. It is never authorization.
pub fn derive_custom_id(
    definition_id: &str,
    execution_id: &str,
    serialized_data: &[u8],
    frame_identity: Option<&str>,
) -> anyhow::Result<CustomId> {
    let mut first = 0xcbf29ce484222325u64;
    let mut second = 0x84222325cbf29ce4u64;
    fn feed(hash: &mut u64, bytes: &[u8]) {
        for byte in bytes {
            *hash ^= u64::from(*byte);
            *hash = hash.wrapping_mul(0x100000001b3);
        }
    }
    fn field(first: &mut u64, second: &mut u64, bytes: &[u8]) {
        let length = (bytes.len() as u64).to_le_bytes();
        feed(first, &length);
        feed(second, &length);
        feed(first, bytes);
        feed(second, bytes);
    }

    // Length-prefix each field so concatenated inputs cannot be ambiguous.
    field(&mut first, &mut second, definition_id.as_bytes());
    field(&mut first, &mut second, execution_id.as_bytes());
    field(&mut first, &mut second, serialized_data);
    match frame_identity {
        Some(identity) => {
            field(&mut first, &mut second, &[1]);
            field(&mut first, &mut second, identity.as_bytes());
        }
        None => field(&mut first, &mut second, &[0]),
    }

    let custom_id = format!("rp:{first:016x}{second:016x}");
    anyhow::ensure!(
        custom_id.chars().count() <= crate::page::limits::CUSTOM_ID_MAX_CHARS,
        "Derived Discord custom ID exceeds the maximum length"
    );
    Ok(CustomId(custom_id))
}

/// In-memory Store for tests and development; it is not durable across restarts.
#[derive(Default)]
pub struct MemoryStore {
    records: std::sync::RwLock<std::collections::HashMap<CustomId, StoreRecord>>,
}
impl Store for MemoryStore {
    fn insert<'a>(&'a self, record: StoreRecord)
        -> BoxFuture<'a, anyhow::Result<()>>
    {
        Box::pin(async move {
            let key = CustomId(record.custom_id.clone());
            let mut records = self.records.write()
                .map_err(|_| anyhow::anyhow!("Memory Store lock was poisoned"))?;
            match records.get(&key) {
                Some(existing) if existing == &record => Ok(()),
                Some(_) => anyhow::bail!("Conflicting Store record for custom ID '{}'", key.0),
                None => {
                    records.insert(key, record);
                    Ok(())
                }
            }
        })
    }
    fn resolve<'a>(&'a self, custom_id: &'a CustomId)
        -> BoxFuture<'a, anyhow::Result<Option<StoreRecord>>>
    {
        Box::pin(async move {
            let records = self.records.read()
                .map_err(|_| anyhow::anyhow!("Memory Store lock was poisoned"))?;
            Ok(records.get(custom_id).cloned())
        })
    }
    fn remove<'a>(&'a self, custom_id: &'a CustomId)
        -> BoxFuture<'a, anyhow::Result<()>>
    {
        Box::pin(async move {
            let mut records = self.records.write()
                .map_err(|_| anyhow::anyhow!("Memory Store lock was poisoned"))?;
            records.remove(custom_id);
            Ok(())
        })
    }
}
